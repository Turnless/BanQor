// Generates src/abi.ts from Foundry build output so the SDK ABI always matches the contracts.
// Run `forge build` in contracts/ first.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../contracts/out");
const pick = (file, name) => JSON.parse(readFileSync(resolve(out, file, `${name}.json`), "utf8")).abi;

const src = `// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit by hand.
export const banqorVaultAbi = ${JSON.stringify(pick("BanQorVault.sol", "BanQorVault"), null, 2)} as const;

export const banqorFactoryAbi = ${JSON.stringify(pick("BanQorFactory.sol", "BanQorFactory"), null, 2)} as const;
`;
writeFileSync(resolve(here, "../src/abi.ts"), src);
console.log("wrote src/abi.ts");
